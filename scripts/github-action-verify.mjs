import { execFileSync } from "node:child_process";
import { appendFileSync, existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

export const STICKY_MARKER = "<!-- metaskill-verify-report -->";

export function buildStickyPrComment(markdownReport, overallStatus) {
  const badge =
    overallStatus === "verified"
      ? "**Status:** `verified` — All contract requirements demonstrated."
      : "**Status:** `incomplete` — Pending or blocked requirements remain.";
  return [
    STICKY_MARKER,
    badge,
    "",
    markdownReport.trim(),
    "",
    "_Generated by `mtsk verify` (`metaskill/verify`)._",
  ].join("\n");
}

function resolveCliEntry(actionRoot, workDir) {
  const fromAction = path.join(actionRoot, "dist", "index.js");
  if (existsSync(fromAction)) return { cmd: process.execPath, prefixArgs: [fromAction] };

  const localBin = path.join(workDir, "node_modules", "mtsk", "dist", "index.js");
  if (existsSync(localBin)) return { cmd: process.execPath, prefixArgs: [localBin] };

  return { cmd: "mtsk", prefixArgs: [] };
}

function setOutput(name, value) {
  const outFile = process.env.GITHUB_OUTPUT;
  if (!outFile) return;
  appendFileSync(outFile, `${name}<<METASKILL_EOF\n${value}\nMETASKILL_EOF\n`, "utf8");
}

async function upsertPrComment({ token, apiUrl, repo, prNumber, body }) {
  const headers = {
    Authorization: `Bearer ${token}`,
    Accept: "application/vnd.github+json",
    "User-Agent": "metaskill-verify-action",
    "Content-Type": "application/json",
  };
  const listUrl = `${apiUrl}/repos/${repo}/issues/${prNumber}/comments?per_page=100`;
  const listRes = await fetch(listUrl, { headers });
  if (!listRes.ok) {
    throw new Error(`Failed to list PR comments (${listRes.status})`);
  }
  const comments = await listRes.json();
  const existing = Array.isArray(comments)
    ? comments.find((c) => typeof c.body === "string" && c.body.includes(STICKY_MARKER))
    : undefined;

  if (existing?.id) {
    const patchUrl = `${apiUrl}/repos/${repo}/issues/comments/${existing.id}`;
    const patchRes = await fetch(patchUrl, {
      method: "PATCH",
      headers,
      body: JSON.stringify({ body }),
    });
    if (!patchRes.ok) {
      throw new Error(`Failed to update PR comment (${patchRes.status})`);
    }
    return;
  }

  const postRes = await fetch(`${apiUrl}/repos/${repo}/issues/${prNumber}/comments`, {
    method: "POST",
    headers,
    body: JSON.stringify({ body }),
  });
  if (!postRes.ok) {
    throw new Error(`Failed to create PR comment (${postRes.status})`);
  }
}

async function main() {
  const actionRoot = process.env.METASKILL_ACTION_ROOT || path.resolve(import.meta.dirname, "..");
  const workDir = path.resolve(process.env.INPUT_WORKDIR || ".");
  const contract = process.env.INPUT_CONTRACT || "SPEC.md";
  const timeout = process.env.INPUT_TIMEOUT || "60000";
  const lang = process.env.INPUT_LANG === "es" ? "es" : "en";
  const failOnIncomplete = process.env.INPUT_FAIL_ON_INCOMPLETE !== "false";
  const postComment = process.env.INPUT_POST_COMMENT !== "false";

  const { cmd, prefixArgs } = resolveCliEntry(actionRoot, workDir);
  const args = [
    ...prefixArgs,
    "verify",
    "--dir",
    workDir,
    "--contract",
    contract,
    "--timeout",
    timeout,
    "--lang",
    lang,
  ];

  let verifyExitCode = 0;
  try {
    execFileSync(cmd, args, { stdio: "inherit", windowsHide: true });
  } catch (err) {
    verifyExitCode = typeof err?.status === "number" ? err.status : 1;
  }

  const reportJsonPath = path.join(workDir, ".agents", "evidence", "report.json");
  const reportMdPath = path.join(workDir, ".agents", "evidence", "report.md");

  let status = verifyExitCode === 0 ? "verified" : "incomplete";
  let markdownReport = existsSync(reportMdPath) ? readFileSync(reportMdPath, "utf8") : "";
  if (existsSync(reportJsonPath)) {
    const parsed = JSON.parse(readFileSync(reportJsonPath, "utf8"));
    status = parsed.overallStatus || status;
  }

  setOutput("status", status);
  setOutput("report-md", reportMdPath);
  setOutput("report-json", reportJsonPath);

  if (postComment && markdownReport && process.env.INPUT_GITHUB_TOKEN) {
    const eventPath = process.env.GITHUB_EVENT_PATH;
    const repo = process.env.GITHUB_REPOSITORY;
    const apiUrl = process.env.GITHUB_API_URL || "https://api.github.com";
    if (eventPath && repo && existsSync(eventPath)) {
      const event = JSON.parse(readFileSync(eventPath, "utf8"));
      const prNumber = event.pull_request?.number || event.issue?.number;
      if (prNumber) {
        await upsertPrComment({
          token: process.env.INPUT_GITHUB_TOKEN,
          apiUrl,
          repo,
          prNumber,
          body: buildStickyPrComment(markdownReport, status),
        });
      }
    }
  }

  if (failOnIncomplete && verifyExitCode !== 0) {
    process.exitCode = verifyExitCode;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((err) => {
    console.error(err instanceof Error ? err.message : String(err));
    process.exitCode = 1;
  });
}
